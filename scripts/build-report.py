db = sqlite3.connect(':memory:')
for migration in sorted((ROOT / 'backend/prisma/migrations').glob('*/migration.sql')):
    db.executescript(migration.read_text(encoding='utf-8'))
tables = [r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")]
schema = {}
dbml = ['// Physical SQLite schema exported from the existing SQL migration.', '// UUID defaults are generated by Prisma, not SQLite.\n']
refs = []
for name in tables:
    columns = list(db.execute(f'PRAGMA table_info("{name}")'))
    foreign = list(db.execute(f'PRAGMA foreign_key_list("{name}")'))
    indexes = [(r, list(db.execute(f'PRAGMA index_info("{r[1]}")'))) for r in db.execute(f'PRAGMA index_list("{name}")')]
    unique = {cols[0][2] for idx, cols in indexes if idx[2] and len(cols) == 1}
    pk = [col[1] for col in columns if col[5]]
    lines = []
    dbml.append(f'Table {name} {{')
    for _, col, typ, nn, default, primary in columns:
        flags = []
        if primary and len(pk) == 1: flags.append('pk')
        if nn: flags.append('not null')
        if col in unique and not primary: flags.append('unique')
        if default is not None: flags.append('default: ' + (f'`{default}`' if default == 'CURRENT_TIMESTAMP' else default))
        dbml.append(f'  {col} {typ.lower()}' + (' [' + ', '.join(flags) + ']' if flags else ''))
        labels = (' PK' if primary else '') + (' FK' if any(f[3] == col for f in foreign) else '') + (' UQ' if col in unique and not primary else '') + (' NN' if nn else '')
        lines.append(f'{col}: {typ}{labels}')
    compound = []
    if len(pk) > 1: compound.append('(' + ', '.join(pk) + ') [pk]')
    for idx, cols in indexes:
        if idx[3] == 'pk': continue
        if len(cols) == 1 and idx[2]: continue
        compound.append('(' + ', '.join(c[2] for c in cols) + ')' + (' [unique]' if idx[2] else ''))
    if compound:
        dbml.append('  indexes {')
        dbml.extend('    ' + value for value in compound)
        dbml.append('  }')
    dbml.append('}\n')
    for foreign_key in foreign:
        _, _, parent, col, parent_col, update, delete, _ = foreign_key
        relation = '-' if col in unique else '>'
        refs.append(f'Ref: {name}.{col} {relation} {parent}.{parent_col} [delete: {delete.lower()}, update: {update.lower()}]')
    schema[name] = (lines, foreign, compound)
(ROOT / 'docs/schema.dbml').write_text('\n'.join(dbml + refs) + '\n', encoding='utf-8')

